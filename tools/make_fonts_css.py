"""
Regenerate css/fonts.css from fonts/*.woff2 (base64-inlined so the app works offline from file://).
Only needed when the font list changes.  Usage: python tools/make_fonts_css.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = [
    ("LS Inter", 400, "inter-latin-400-normal.woff2"),
    ("LS Inter", 700, "inter-latin-700-normal.woff2"),
    ("LS Inter", 900, "inter-latin-900-normal.woff2"),
    ("LS Roboto Condensed", 700, "roboto-condensed-latin-700-normal.woff2"),
    ("LS Bebas Neue", 400, "bebas-neue-latin-400-normal.woff2"),
    ("LS Fredoka", 600, "fredoka-latin-600-normal.woff2"),
    ("LS Caveat", 700, "caveat-latin-700-normal.woff2"),
    ("LS Permanent Marker", 400, "permanent-marker-latin-400-normal.woff2"),
    ("LS Archivo Black", 400, "archivo-black-latin-400-normal.woff2"),
    ("LS Space Mono", 700, "space-mono-latin-700-normal.woff2"),
    ("LS Pacifico", 400, "pacifico-latin-400-normal.woff2"),
]

lines = ["/* ThermaLabel embedded fonts (generated by tools/make_fonts_css.py, see docs/FONTS.md). Inline so file:// works offline. */"]
for family, weight, name in FONTS:
    b64 = base64.b64encode((ROOT / "fonts" / name).read_bytes()).decode("ascii")
    lines.append(f'@font-face{{font-family:"{family}";font-weight:{weight};font-style:normal;font-display:block;'
                 f'src:url(data:font/woff2;base64,{b64}) format("woff2")}}')
(ROOT / "css" / "fonts.css").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote css/fonts.css")
